"""Write docs/RESULTS.md from results/*.json so the document cannot disagree with the data."""
import json
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "results"
L = lambda n: json.loads((R / n).read_text())
tr, pat = L("train_summary.json"), L("pattern.json")
rows = []
for label, key in [("NMS-free, conf 0.25 (default)", "default"), ("NMS-free, tuned on val", "nms_free"), ("Class NMS, tuned on val", "class_nms")]:
    e, r = L(f"eval_report_{key}.json"), L(f"run_report_{key}.json")
    rows.append(f"| {label} | {r['conf']:.2f} | {e['overall_precision']*100:.1f} | {e['overall_recall']*100:.1f} | "
                f"{e['pipeline_end_to_end_field_accuracy']*100:.1f} | {e['duplicate_boxes']} | {e['missed_fields']} |")
b = L("eval_report_class_nms.json")
m = pat["modes"]
out = f"""# Results

Generated by `scripts/make_results_md.py` from `results/*.json`. Synthetic data, CPU only (2 cores), one training seed.

## Training
YOLO26n, {tr['epochs']} epochs, {tr['train_seconds']/60:.0f} min on CPU. Validation mAP50 {tr['val_map50']}, mAP50-95 {tr['val_map50_95']}.

## Test split (60 documents, 300 fields, 240 with text)
| Variant | conf | P % | R % | End-to-end % | Duplicate boxes | Missed fields |
|---|---|---|---|---|---|---|
""" + "\n".join(rows) + f"""

Confidence for the tuned variants was chosen on the validation split only (max detection F1).
Full-page Tesseract found {b['fullpage_tesseract_field_capture']*100:.1f}% of text strings anywhere on the page (lenient, no field attribution), {b['fullpage_tesseract_seconds_per_doc']:.2f} s per document.

## Inference pattern ({pat['docs']} documents, {pat['partitions']} partitions, {pat['repeats']} timed runs after warm-up)
| Pattern | Seconds (mean +/- sd) | Docs/s | Speedup |
|---|---|---|---|
| Row-wise UDF, model per row | {m['row_udf']['seconds_mean']} +/- {m['row_udf']['seconds_sd']} | {m['row_udf']['docs_per_second']} | 1.0 |
| mapInPandas, Arrow batch 1 | {m['partition_b1']['seconds_mean']} +/- {m['partition_b1']['seconds_sd']} | {m['partition_b1']['docs_per_second']} | {m['partition_b1']['speedup_vs_row_udf']} |
| mapInPandas, Arrow batch 16 | {m['partition_b16']['seconds_mean']} +/- {m['partition_b16']['seconds_sd']} | {m['partition_b16']['docs_per_second']} | {m['partition_b16']['speedup_vs_row_udf']} |

## Not measured
GPU, EMR, multi-node scaling, cluster cold start, cost, Amazon Textract, real scanned documents.
"""
(R.parent / "docs" / "RESULTS.md").write_text(out)
print(out[:400])
